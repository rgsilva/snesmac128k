#!/usr/bin/env python3
"""Generate the zoom-out (2x2 downscale) lookup tables -> maczoom_tab.h.

The zoomed view shows the whole 512x342 Mac screen at 256x171 with FOUR
gray levels: each output pixel covers a 2x2 input block, and the count of
black pixels in the block (0-4) picks a color. The Mac's 50% dithered
desktop averages to a real gray instead of collapsing to black (OR) or
white (AND), and 1px window borders stay visible as dark gray.

Three tables, all indexed by bytes, so the renderer does no per-pixel bit
fiddling:

  ZPC[b]   u16: the 4 horizontal pair-counts of input byte b (bit 7 = the
           leftmost pixel), packed one per nibble, leftmost pair in the
           high nibble. Row-pair sum = ZPC[top] + ZPC[bottom] — nibble
           sums never exceed 4, so a plain 16-bit add never carries
           across nibbles.
  ZP0[x] / ZP1[x]  u8: 2 output pixels' plane-0 / plane-1 bits (bit 1 =
           the left pixel) for a byte x holding two summed nibbles.

Color mapping (count -> CGRAM index): 0->0 white, 1->2 light gray,
2->3 dark gray, 3->3, 4->1 black. Index 1 stays black so the normal
(1-bit) view's palette is untouched; the grays live in the otherwise
unused colors 2/3. Plane bits: index = plane1<<1 | plane0.
"""
import sys

LEVEL = [0, 2, 3, 3, 1]          # black-count 0..4 -> CGRAM color index

def pair_counts(b):
    out = 0
    for pair in range(4):        # pair 0 = bits 7,6 (leftmost)
        hi = (b >> (7 - pair * 2)) & 1
        lo = (b >> (6 - pair * 2)) & 1
        out |= (hi + lo) << ((3 - pair) * 4)
    return out

def planes(x):                   # x = two summed nibbles (left in high)
    p0 = p1 = 0
    for i, shift in ((1, 4), (0, 0)):   # left pixel -> bit 1
        c = (x >> shift) & 0xF
        c = c if c <= 4 else 4          # impossible indexes: clamp
        p0 |= (LEVEL[c] & 1) << i
        p1 |= ((LEVEL[c] >> 1) & 1) << i
    return p0, p1

def fmt(vals, per_line=8, w=6):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("  " + ", ".join(f"0x{v:0{w-2}X}" for v in vals[i:i+per_line]) + ",")
    return "\n".join(lines)

zpc = [pair_counts(b) for b in range(256)]
zp0, zp1 = zip(*(planes(x) for x in range(256)))

with open(sys.argv[1], "w") as f:
    f.write("/* generated by tools/mkzoomtab.py — zoom-out downscale tables */\n")
    f.write("static const uint16_t ZPC[256] = {\n" + fmt(zpc) + "\n};\n")
    f.write("static const uint8_t ZP0[256] = {\n" + fmt(zp0, 16, 4) + "\n};\n")
    f.write("static const uint8_t ZP1[256] = {\n" + fmt(zp1, 16, 4) + "\n};\n")
print("maczoom_tab.h written")
