#!/usr/bin/env python3
"""Generate the on-screen keyboard -> mackbd_tab.h (the snes86 pattern,
re-cut for the Mac: same controls, Mac virtual keycodes instead of PC
scancodes, and 2bpp BG2 tiles instead of the mode-5 console).

Emits:
  KBD_FONT[]   2bpp tiles: tile 0 transparent, tile 1 solid panel, then one
               tile per glyph used (plane 0 = font8x8 bits, plane 1 = solid,
               so pixels read 2 (panel) / 3 (ink) — fully opaque over BG1).
  KBD_MAP[5][32]  tile index per keyboard cell (5 rows, 32 columns).
  KBD_GRID[5][32] key index per cell (0xFF = dead space) for d-pad nav.
  KBD_KEYS[]   {row, x, w, ch, shifted_ch, mac_keycode} per key.

Mac virtual keycodes are the classic US set (Inside Macintosh); the event
message posted is (keycode << 8) | char, char picked by the sticky shift.
"""
import re
import sys

# ---- font8x8 (public domain, vendored) ----
FONT = {}
src = open(__file__.rsplit("/", 1)[0] + "/font8x8_basic.h").read()
block = src[src.index("font8x8_basic[128][8]"):]
hexes = re.findall(r"0x[0-9A-Fa-f]{2}", block)
for i in range(128):
    FONT[chr(i)] = [int(h, 16) for h in hexes[i * 8:i * 8 + 8]]

MACK = {}
for c, k in zip("asdfhgzxcv", range(0x0A)):
    MACK[c] = k
MACK["b"] = 0x0B
for c, k in zip("qwer", range(0x0C, 0x10)): MACK[c] = k
MACK.update({"y": 0x10, "t": 0x11})
for c, k in zip("123465", range(0x12, 0x18)): MACK[c] = k
MACK.update({"=": 0x18, "9": 0x19, "7": 0x1A, "-": 0x1B, "8": 0x1C, "0": 0x1D,
             "]": 0x1E, "o": 0x1F, "u": 0x20, "[": 0x21, "i": 0x22, "p": 0x23,
             "l": 0x25, "j": 0x26, "'": 0x27, "k": 0x28, ";": 0x29, "\\": 0x2A,
             ",": 0x2B, "/": 0x2C, "n": 0x2D, "m": 0x2E, ".": 0x2F, "`": 0x32})
K_RET, K_TAB, K_SPC, K_BS = 0x24, 0x30, 0x31, 0x33

SH = {}
for a, b in zip("1234567890-=[]\\;'`,./", "!@#$%^&*()_+{}|:\"~<>?"):
    SH[a] = b

# rows of (label, char, shifted, keycode); char 0xFF = the sticky shift
ROWS = [
    [(c, ord(c), ord(SH[c]), MACK[c]) for c in "1234567890-="] + [("BS", 8, 8, K_BS)],
    [(c, ord(c), ord(c.upper()), MACK[c]) for c in "qwertyuiop"]
    + [(c, ord(c), ord(SH[c]), MACK[c]) for c in "[]\\"],
    [(c, ord(c), ord(c.upper()), MACK[c]) for c in "asdfghjkl"]
    + [(c, ord(c), ord(SH[c]), MACK[c]) for c in ";'"] + [("RET", 13, 13, K_RET)],
    [(c, ord(c), ord(c.upper()), MACK[c]) for c in "zxcvbnm"]
    + [(c, ord(c), ord(SH[c]), MACK[c]) for c in ",./`"] + [("SHIFT", 0xFF, 0xFF, 0)],
    [("SPACE", 32, 32, K_SPC), ("TAB", 9, 9, K_TAB)],
]

grid = [[0xFF] * 32 for _ in range(5)]
cells = [[" "] * 32 for _ in range(5)]
keys = []
for r, rowkeys in enumerate(ROWS):
    x = 1
    for label, ch, sh, kc in rowkeys:
        idx = len(keys)
        keys.append((r, x, len(label), ch, sh, kc))
        for i, c in enumerate(label):
            cells[r][x + i] = c.upper()
            grid[r][x + i] = idx
        x += len(label) + 1
    assert x <= 33, f"row {r} overflows: {x}"

# glyph set -> tiles (0 transparent, 1 panel)
used = sorted({c for row in cells for c in row})
ch2tile = {}
tiles = [bytes(16), bytes([0, 0xFF] * 8)]        # transparent, solid panel
for c in used:
    if c == " ":
        ch2tile[c] = 1
        continue
    rows8 = FONT.get(c) or FONT.get(c.lower()) or [0] * 8
    t = bytearray()
    for y in range(8):
        bits = rows8[y]
        rev = int(f"{bits:08b}"[::-1], 2)        # font8x8 is LSB-left
        t += bytes([rev, 0xFF])                  # plane0 glyph, plane1 solid
    ch2tile[c] = len(tiles)
    tiles.append(bytes(t))

# inverted copies (for the selected-key highlight, palette-bit-free): swap
# panel<->ink by flipping plane 0 (plane 1 stays solid). tile N+i is the
# inverse of tile i.
nbase = len(tiles)
inv = []
for t in tiles:
    it = bytearray()
    for j in range(0, 16, 2):
        it += bytes([(~t[j]) & 0xFF, t[j + 1]])   # plane0 inverted, plane1 kept
    inv.append(bytes(it))
NORMAL_TILES = len(tiles)
tiles += inv

def cfmt(vals, per=12, w=4):
    return "\n".join("  " + ", ".join(f"0x{v:0{w-2}X}" for v in vals[i:i+per]) + ","
                     for i in range(0, len(vals), per))

with open(sys.argv[1], "w") as f:
    f.write("/* generated by tools/mkkbd.py — on-screen keyboard tables */\n")
    flat = b"".join(tiles)
    f.write(f"#define KBD_NTILES {len(tiles)}\n")
    f.write(f"#define KBD_HILITE {NORMAL_TILES}   /* selected cell tile += this */\n")
    f.write("static const uint8_t KBD_FONT[] = {\n" + cfmt(list(flat), 16) + "\n};\n")
    f.write("static const uint8_t KBD_MAP[5][32] = {\n")
    for r in range(5):
        f.write("{" + ",".join(str(ch2tile[c]) for c in cells[r]) + "},\n")
    f.write("};\n")
    f.write("static const uint8_t KBD_GRID[5][32] = {\n")
    for r in range(5):
        f.write("{" + ",".join(f"0x{v:02X}" for v in grid[r]) + "},\n")
    f.write("};\n")
    f.write(f"#define KBD_NKEYS {len(keys)}\n")
    f.write("static const struct { uint8_t row, x, w, ch, sh, kc; } KBD_KEYS[] = {\n")
    for k in keys:
        f.write("  {%d,%d,%d,0x%02X,0x%02X,0x%02X},\n" % k)
    f.write("};\n")
print(f"mackbd_tab.h: {len(keys)} keys, {len(tiles)} tiles")
