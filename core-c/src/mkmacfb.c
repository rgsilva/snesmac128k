/* M4: boot the Mac on the host, capture the framebuffer, and emit the center
** 256x224 crop as SNES 2bpp tile data for the display ROM. The crop is
** byte-aligned (x in [128,384) => Mac bytes 16..47), so a Mac framebuffer byte
** (8 px, MSB-left, 1=black) maps directly to a 2bpp plane-0 row (plane 1 = 0).
** Output (stdout) is a C header; a downsampled preview goes to stderr.
**
** The framebuffer is derived from the (Apple copyright) ROM, so the generated
** header is gitignored. */
#include <stdio.h>
#include <stdlib.h>
#include "mac.h"

#define X0 16   /* Mac byte column (pixel 128) */
#define Y0 59   /* top line (centers 224 in 342) */
#define TW 32   /* tiles across (256 px) */
#define TH 28   /* tiles down  (224 px) */

int main(int argc, char **argv){
  const char *path = argc > 1 ? argv[1] : "roms/mac128k.rom";
  long steps = argc > 2 ? atol(argv[2]) : 15000000L;
  static uint8_t rom[65536];
  FILE *f = fopen(path, "rb");
  if (!f) { fprintf(stderr, "cannot open %s\n", path); return 1; }
  if (fread(rom, 1, 65536, f) != 65536) { fprintf(stderr, "ROM not 64KB\n"); return 1; }
  fclose(f);

  mac_init(rom);
  for (long i = 0; i < steps; i++) mac_step();
  uint8_t *fb = mac_ram_ptr() + 0x1A700;

  /* preview to stderr (every 2nd px / 3rd line) so we can confirm the capture */
  fprintf(stderr, "captured crop (256x224, downsampled):\n");
  for (int y = 0; y < 224; y += 3) {
    for (int x = 0; x < 256; x += 2) {
      uint8_t b = fb[(Y0 + y) * 64 + X0 + ((x) >> 3)];
      putc(((b >> (7 - (x & 7))) & 1) ? '#' : '.', stderr);
    }
    putc('\n', stderr);
  }

  /* emit tiles: row-major (ty,tx), tile index = ty*TW+tx */
  printf("/* generated by mkmacfb from the user's Mac ROM — derived, gitignored */\n");
  printf("#define MACFB_TW %d\n#define MACFB_TH %d\n", TW, TH);
  printf("static const unsigned char MACFB_TILES[%d*%d*16] = {\n", TW, TH);
  for (int ty = 0; ty < TH; ty++) {
    for (int tx = 0; tx < TW; tx++) {
      printf("  ");
      for (int row = 0; row < 8; row++)
        printf("0x%02X,0x00,", fb[(Y0 + ty * 8 + row) * 64 + X0 + tx]);
      printf("\n");
    }
  }
  printf("};\n");
  return 0;
}
