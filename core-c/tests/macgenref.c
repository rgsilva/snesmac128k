/* Host reference generator for the Mac-machine SNES parity ROM.
** Boots the real ROM through the machine model for N steps (NO disk — the
** early boot doesn't touch it, so this validates CPU + VIA + overlay + IWM
** sense on Calypsi), folding a cumulative CPU-state hash each step and a final
** RAM hash, and emits snes/build/macparity_ref.h for the SNES side to match. */
#include <stdio.h>
#include <stdlib.h>
#include "mac.h"
#include "macparity_hash.h"

int main(int argc, char **argv){
  const char *rompath = argc > 1 ? argv[1] : "roms/mac128k.rom";
  long n = argc > 2 ? atol(argv[2]) : 100000L;
  static uint8_t rom[65536];
  FILE *f = fopen(rompath, "rb");
  if (!f) { fprintf(stderr, "cannot open %s\n", rompath); return 1; }
  if (fread(rom, 1, 65536, f) != 65536) { fprintf(stderr, "ROM not 64KB\n"); return 1; }
  fclose(f);

  mac_init(rom);                       /* no mac_set_disk: HLE stays off */
  uint32_t h = MACP_FNV_INIT;
  long i;
  for (i = 0; i < n; i++) { mac_step(); h = macp_hash_cpu(h); }

  uint32_t rh = MACP_FNV_INIT;
  { uint8_t *ram = mac_ram_ptr(); uint32_t k;
    for (k = 0; k < 0x20000u; k++) rh = macp_fnv1(rh, ram[k]); }

  printf("/* generated by macgenref.c — host reference for macparity.c */\n");
  printf("#ifndef MACPARITY_REF_H\n#define MACPARITY_REF_H\n");
  printf("#define MACP_N        %ldul\n", n);
  printf("#define MACP_CPUHASH  0x%08lXul\n", (unsigned long)h);
  printf("#define MACP_RAMHASH  0x%08lXul\n", (unsigned long)rh);
  printf("#endif\n");
  fprintf(stderr, "macgenref: N=%ld cpuhash=%08lX ramhash=%08lX vbl=%u overlay=%d pc=%06X\n",
          n, (unsigned long)h, (unsigned long)rh, mac_vbl_count(), mac_overlay(), m68kc.pc);
  return 0;
}
