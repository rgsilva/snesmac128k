#!/usr/bin/env bash
# M2: prove the Calypsi-compiled lean 68000 core matches the host core on real
# SNES hardware (Mesen). Builds host per-step reference hashes, bakes them into
# the ROM, runs the ROM headless; the ROM compares in C and mails the first
# mismatching step (if any). Mirrors snespico8's snesparity.
set -euo pipefail
cd "$(dirname "$0")"          # core-c/tests
mkdir -p build

echo "== host reference (host build of the same m68k.c) =="
cc -O2 -std=c11 -I../src -o build/parity_host parity_host.c ../src/m68k.c
{
  echo "/* generated by parity_snes.sh — host per-step reference hashes */"
  echo "#define PARITY_TRACE_N 64"
  echo "static const uint32_t PARITY_REF_TRACE[PARITY_TRACE_N] = {"
  ./build/parity_host trace
  echo "};"
  echo "#define PARITY_REF 0x$(./build/parity_host)ul"
} > parity_ref.h
echo "   host final hash = 0x$(./build/parity_host)"

echo "== SNES parity ROM (Calypsi build of the same m68k.c) =="
make -C ../../snes test-parity
